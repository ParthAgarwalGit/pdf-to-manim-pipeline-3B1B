"""Output manifest schema for Persistence Agent."""

from datetime import datetime
from typing import List, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class OutputFile(BaseModel):
    """Information about a single output file."""
    
    path: str = Field(
        ...,
        description="Path to the file relative to output_directory"
    )
    size_bytes: int = Field(
        ...,
        ge=0,
        description="File size in bytes"
    )
    type: str = Field(
        ...,
        description="File type (animation_code|narration_script|storyboard|manifest|report)"
    )
    
    @field_validator('type')
    @classmethod
    def validate_type(cls, v: str) -> str:
        """Validate file type is one of the allowed values."""
        allowed_types = {
            'animation_code',
            'narration_script',
            'storyboard',
            'manifest',
            'report',
            'ocr_output',
            'log',
            'scene_video',
            'scene_audio',
            'composed_video',
            'final_video',
            'lesson_script',
        }
        if v not in allowed_types:
            raise ValueError(
                f"type must be one of {allowed_types}, got '{v}'"
            )
        return v


class RunConfig(BaseModel):
    """Records what the run actually did."""

    dry_run: bool = Field(
        ...,
        description="Whether this run was a dry run (stops after storyboard)"
    )
    enable_render: bool = Field(
        ...,
        description="Whether video rendering was enabled"
    )
    enable_tts: bool = Field(
        ...,
        description="Whether TTS generation was enabled"
    )
    render_quality: str = Field(
        ...,
        description="Render quality setting (low/medium/high)"
    )
    tts_voice: str = Field(
        ...,
        description="TTS voice selection"
    )
    tts_first: bool = Field(
        default=False,
        description="Whether measured narration set scene timing before codegen"
    )


class SceneRecord(BaseModel):
    """Per-scene fingerprints and artifacts; a revision run reuses them.

    Paths are relative to the run's output_directory.
    """

    scene_id: str
    beat_ids: List[str] = Field(default_factory=list)
    beats_fp: str = Field(..., description="Fingerprint of the scene's source beats")
    narration_fp: str = Field(..., description="Fingerprint of narration text + voice")
    visual_fp: str = Field(..., description="Fingerprint of visual plan + timing + quality")
    code_path: Optional[str] = None
    video_path: Optional[str] = None
    video_duration_seconds: Optional[float] = None
    audio_path: Optional[str] = None
    audio_duration_seconds: Optional[float] = None
    reused_video_from: Optional[str] = Field(
        default=None,
        description="Parent-run scene_id whose code and render this scene reused",
    )
    reused_audio_from: Optional[str] = Field(
        default=None,
        description="Parent-run scene_id whose narration audio this scene reused",
    )


class FailedSceneManifest(BaseModel):
    """Information about a scene that failed to generate."""

    scene_id: str = Field(..., description="Unique identifier for the failed scene")
    error: str = Field(..., description="Error message describing the failure")


class CostSummary(BaseModel):
    """Aggregate LLM / TTS spend for the run, in USD.

    Populated by the orchestrator from ``CostTracker.get_instance()`` after
    every stage finishes. Lets operators audit per-PDF spend without parsing
    a separate cost report.
    """

    total_usd: float = Field(
        ...,
        ge=0.0,
        description="Total estimated USD spend across all providers and models",
    )
    by_provider: dict = Field(
        default_factory=dict,
        description="USD spend per provider (e.g. {'openai': 0.42, 'anthropic': 0.18})",
    )
    by_model: dict = Field(
        default_factory=dict,
        description="USD spend per model (e.g. {'gpt-5': 0.30, 'claude-sonnet-4-6': 0.12})",
    )
    by_call_type: dict = Field(
        default_factory=dict,
        description="USD spend per call type (chat, completion, tts, ...)",
    )
    call_count: int = Field(
        default=0,
        ge=0,
        description="Total number of tracked API calls in this run",
    )


class OutputManifest(BaseModel):
    """
    Complete manifest of all output files generated by the pipeline.
    
    Written by Persistence Agent to manifest.json in the output directory.
    """
    
    output_directory: str = Field(
        ...,
        description="Absolute path to the output directory"
    )
    files: List[OutputFile] = Field(
        ...,
        description="Array of all generated files with metadata"
    )
    timestamp: datetime = Field(
        ...,
        description="ISO8601 timestamp when the manifest was created"
    )
    status: str = Field(
        ...,
        description="Overall pipeline status (SUCCESS|PARTIAL_SUCCESS|FAILURE|CRITICAL_FAILURE)"
    )
    scene_success_rate: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Fraction of scenes that generated successfully (0-1)"
    )
    total_scenes: int = Field(
        ...,
        ge=0,
        description="Total number of scenes in the storyboard"
    )
    successful_scenes: int = Field(
        ...,
        ge=0,
        description="Number of scenes that generated successfully"
    )
    failed_scenes: List[FailedSceneManifest] = Field(
        default_factory=list,
        description="Array of scenes that failed to generate"
    )
    run_config: Optional[RunConfig] = Field(
        default=None,
        description="Effective runtime configuration for this run"
    )
    final_video_path: Optional[str] = Field(
        default=None,
        description="Relative path to the final composed video (None if render was skipped)"
    )
    cost_summary: Optional[CostSummary] = Field(
        default=None,
        description="Aggregate USD spend for the run (None if cost tracking was skipped)"
    )
    warning_count: Optional[int] = Field(
        default=None,
        description="Number of WARNING+ log records captured during the run "
                    "(persisted to warnings.log in the output directory)"
    )
    delivered_scenes: Optional[int] = Field(
        default=None,
        description="Scenes that made it into the rendered video (None when "
                    "rendering was skipped). successful_scenes only counts "
                    "code generation; this is the honest delivery number."
    )
    lost_scenes: List[str] = Field(
        default_factory=list,
        description="scene_ids that generated code but failed to render and "
                    "could not be salvaged — missing from the final video"
    )
    scenes: List[SceneRecord] = Field(
        default_factory=list,
        description="Per-scene fingerprints and artifact paths, in video order"
    )

    @field_validator('status')
    @classmethod
    def validate_status(cls, v: str) -> str:
        """Validate status is one of the allowed values."""
        allowed_statuses = {'SUCCESS', 'PARTIAL_SUCCESS', 'FAILURE', 'CRITICAL_FAILURE'}
        if v not in allowed_statuses:
            raise ValueError(
                f"status must be one of {allowed_statuses}, got '{v}'"
            )
        return v
    
    @model_validator(mode='after')
    def validate_scene_success_rate_consistency(self) -> 'OutputManifest':
        """Ensure successful_scenes <= total_scenes and rate is consistent."""
        if self.successful_scenes > self.total_scenes:
            raise ValueError(
                f"successful_scenes ({self.successful_scenes}) cannot exceed "
                f"total_scenes ({self.total_scenes})"
            )
        if self.total_scenes == 0:
            expected_rate = 0.0
        else:
            expected_rate = self.successful_scenes / self.total_scenes
        
        # Allow small floating point differences
        if abs(self.scene_success_rate - expected_rate) > 0.001:
            raise ValueError(
                f"scene_success_rate ({self.scene_success_rate}) is inconsistent with "
                f"successful_scenes ({self.successful_scenes}) / total_scenes ({self.total_scenes}) = {expected_rate}"
            )
        return self
    
    @field_validator('output_directory')
    @classmethod
    def validate_output_directory(cls, v: str) -> str:
        """Ensure output_directory is not empty."""
        if not v or not v.strip():
            raise ValueError("output_directory cannot be empty")
        return v
    
    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "output_directory": "/path/to/output/linear_algebra/2024-01-15T10-30-00",
                "files": [
                    {
                        "path": "scene_intro_001.py",
                        "size_bytes": 2048,
                        "type": "animation_code"
                    },
                    {
                        "path": "narration_script.txt",
                        "size_bytes": 5120,
                        "type": "narration_script"
                    },
                    {
                        "path": "storyboard.json",
                        "size_bytes": 10240,
                        "type": "storyboard"
                    },
                    {
                        "path": "processing_report.json",
                        "size_bytes": 1024,
                        "type": "report"
                    },
                    {
                        "path": "manifest.json",
                        "size_bytes": 2048,
                        "type": "manifest"
                    }
                ],
                "timestamp": "2024-01-15T10:35:00Z",
                "status": "SUCCESS",
                "scene_success_rate": 1.0,
                "total_scenes": 10,
                "successful_scenes": 10,
                "failed_scenes": []
            }
        }
    )
